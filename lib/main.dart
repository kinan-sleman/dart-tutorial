void main() {
  // Switch Case
  var grade = 'A';
  switch (grade) {
    case 'A':
      print('Excellent!');
      break;
    case 'B':
      print('Good job!');
      break;
    case 'C':
      print('You can do better.');
      break;
    case 'D':
      print('Needs improvement.');
      break;
    case 'F':
      print('Failing grade.');
      break;
    default:
      print('Invalid grade.');
  }
}