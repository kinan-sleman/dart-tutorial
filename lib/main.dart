void main() {
  // -------------------- String DataType --------------------:
  String name = "John Doe";
  name = "Jane Doe"; // Reassigning a new value to the variable
  print(name); // Output: Jane Doe

  String FirstName = "John";
  String LastName = "Doe";
  print("My Full Name is: $FirstName $LastName"); // Using string interpolation
  // -------------------- Int DataType --------------------:
  int age = 30;
  age = 31; // Reassigning a new value to the variable
  print(age); // Output: 31
  // -------------------- double DataType --------------------:
  double weight = 3;
  weight = 3.5; // Reassigning a new value to the variable  
  print(weight); // Output: 3.5
  // -------------------- bool DataType --------------------:
  bool isStudent = true;
  isStudent = false; // Reassigning a new value to the variable
  print(isStudent); // Output: false
}